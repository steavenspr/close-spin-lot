var state = {
  filter: "open",
  query: "",
  selectedKey: "",
  phase: "idle",
  closed: [],
  closingStep: 0,
  closingTimer: null,
  countTimers: [],
  toastTimer: null,
};

function init() {
  bindEvents();
  search();
}

function bindEvents() {
  document.getElementById("inv700-btn-load").addEventListener("click", search);
  document.getElementById("inv700-search").addEventListener("keydown", function (e) {
    if (e.key === "Enter") search();
  });
  document.getElementById("inv700-filter-open").addEventListener("click", function () { setFilter("open"); });
  document.getElementById("inv700-filter-all").addEventListener("click", function () { setFilter("all"); });
  document.getElementById("inv700-lot-list-body").addEventListener("click", function (e) {
    var row = e.target.closest(".inv700-lot-row");
    if (row) selectLot(row.dataset.lotKey);
  });
  document.getElementById("inv700-btn-close").addEventListener("click", confirmClose);
  document.getElementById("inv700-btn-clear").addEventListener("click", clearSelection);
}

function lotIsClosed(key) {
  var lot = LOTS[key];
  return Boolean(lot && (lot.presetClosed || state.closed.indexOf(key) >= 0));
}

function matchLots() {
  var needle = state.query.trim().toUpperCase();
  return Object.keys(LOTS)
    .filter(function (key) {
      var lot = LOTS[key];
      var isOpen = !lotIsClosed(key);
      if (state.filter === "open" && !isOpen) return false;
      if (!needle) return true;
      return (
        key.indexOf(needle) >= 0 ||
        lot.productNo.toUpperCase().indexOf(needle) >= 0 ||
        lot.yarnFlg.toUpperCase().indexOf(needle) >= 0 ||
        lot.mcode.indexOf(needle) >= 0
      );
    })
    .sort(function (a, b) { return b.localeCompare(a); });
}

function setFilter(f) {
  state.filter = f;
  document.querySelectorAll(".inv700-btn--filter").forEach(function (btn) {
    btn.classList.toggle("is-active", btn.dataset.filter === f);
  });
  search();
}

function search() {
  state.query = document.getElementById("inv700-search").value;
  var keys = matchLots();
  var showList = keys.length > 0;

  toggle("inv700-no-match", !showList);
  toggle("inv700-workspace", showList);

  if (!showList) {
    clearDetail();
    return;
  }

  renderList(keys);

  if (keys.length === 1) {
    selectLot(keys[0]);
  } else if (state.selectedKey && keys.indexOf(state.selectedKey) >= 0) {
    selectLot(state.selectedKey);
  } else {
    state.selectedKey = "";
    state.phase = "idle";
    clearDetail();
  }
}

function selectLot(key) {
  if (!LOTS[key] || state.phase === "closing") return;

  state.selectedKey = key;
  var closed = lotIsClosed(key);
  state.phase = closed ? "closed" : "loaded";
  state.closingStep = closed ? (LOTS[key].impact || []).length : 0;

  renderList(matchLots());
  renderDetail();
  flash("Lot " + key + " loaded");
}

function renderList(keys) {
  var body = document.getElementById("inv700-lot-list-body");
  var ws = document.getElementById("inv700-workspace");
  var showList = keys.length > 0;

  document.getElementById("inv700-lot-count").textContent = keys.length + " lot" + (keys.length !== 1 ? "s" : "");
  ws.classList.toggle("inv700-workspace--multi", showList);
  toggle("inv700-lot-list", showList);

  body.innerHTML = keys.map(function (key) {
    var lot = LOTS[key];
    var closed = lotIsClosed(key);
    var sel = key === state.selectedKey ? " is-selected" : "";
    var stClass = closed ? "inv700-lot-row__status--ok" : "inv700-lot-row__status--sc";
    var st = closed ? "OK" : "SC";
    return (
      '<button type="button" class="inv700-lot-row' + sel + '" data-lot-key="' + esc(key) + '">' +
      '<div class="inv700-lot-row__top">' +
      '<span class="inv700-lot-row__no">' + esc(key) + "</span>" +
      '<span class="inv700-lot-row__status ' + stClass + '">' + st + "</span>" +
      "</div>" +
      '<div class="inv700-lot-row__sub">' +
      esc(lot.yarnFlg) + " · " + esc(lot.mcode) + " · " + esc(lot.dateSch) +
      "</div></button>"
    );
  }).join("");
}

function renderDetail() {
  var lot = LOTS[state.selectedKey];
  if (!lot) {
    clearDetail();
    return;
  }

  var closed = lotIsClosed(state.selectedKey) || state.phase === "closed";
  var closing = state.phase === "closing";

  toggle("inv700-detail-empty", false);
  toggle("inv700-detail-content", true);
  toggle("inv700-action-bar", true);

  var hero = document.getElementById("inv700-lot-hero");
  hero.classList.toggle("is-closed", closed);
  hero.classList.toggle("is-closing", closing);
  toggle("inv700-stamp", closed);
  toggle("inv700-scan", !closed && !closing);

  document.getElementById("inv700-lot-no").textContent = lot.lotNo;
  document.getElementById("inv700-lot-id").textContent = "lot_id " + lot.lotId;
  document.getElementById("inv700-product").textContent = lot.productNo;
  document.getElementById("inv700-yarn").textContent = lot.yarnFlg;
  document.getElementById("inv700-mcode").textContent = lot.mcode;
  document.getElementById("inv700-date-sch").textContent = lot.dateSch;

  animateMetric("inv700-qty-ord", lot.qtyOrd, 1);
  animateMetric("inv700-qty-rec", lot.qtyRec);
  animateMetric("inv700-qoh", lot.qoh);
  animateMetric("inv700-kgs1", lot.kgs1);
  animateMetric("inv700-kgs2", lot.kgs2);

  setStatus(closed ? "closed" : closing ? "closing" : "open");

  var impact = (lot.impact || []).filter(function (s) { return s.count > 0; });
  var total = impact.reduce(function (n, s) { return n + s.count; }, 0);
  document.getElementById("inv700-impact-summary").textContent = total + " record" + (total !== 1 ? "s" : "");

  var listHtml = impact.map(function (s, i) {
    var done = closed || (closing && i < state.closingStep);
    var active = closing && i + 1 === state.closingStep;
    return (
      '<li class="inv700-impact-item' + (done ? " is-done" : "") + (active ? " is-active" : "") + '">' +
      '<span class="inv700-impact-item__dot"></span>' +
      '<span class="inv700-impact-item__label">' + esc(s.label) + "</span>" +
      '<span class="inv700-impact-item__sub">' + esc(s.sub) + "</span>" +
      (done ? '<span class="inv700-impact-item__done">Closed</span>' : "") +
      "</li>"
    );
  }).join("");
  document.getElementById("inv700-impact-list").innerHTML = listHtml;

  var pct = closed ? 100 : closing ? (state.closingStep / impact.length) * 100 : 0;
  toggle("inv700-progress", closing || closed);
  var bar = document.getElementById("inv700-progress-bar");
  bar.style.width = pct + "%";
  bar.classList.toggle("is-closed", closed);

  updateActionBar(lot, closed, closing);
}

function updateActionBar(lot, closed, closing) {
  document.getElementById("inv700-action-lot").textContent = lot.lotNo;
  document.getElementById("inv700-action-msg").textContent =
    closed ? "Archived" : closing ? "Running cascade…" : "Ready to close";

  var btn = document.getElementById("inv700-btn-close");
  btn.disabled = closed || closing;
  btn.textContent = closed ? "Already closed" : closing ? "Closing…" : "Close SPIN-LOT";
}

function setStatus(mode) {
  var pill = document.getElementById("inv700-status");
  pill.className = "inv700-pill";
  if (mode === "open") {
    pill.classList.add("inv700-pill--open");
    pill.textContent = "Open";
  } else if (mode === "closing") {
    pill.classList.add("inv700-pill--closing");
    pill.textContent = "Closing…";
  } else if (mode === "closed") {
    pill.classList.add("inv700-pill--closed");
    pill.textContent = "Closed";
  } else {
    pill.classList.add("inv700-hidden");
    pill.textContent = "";
  }
}

function confirmClose() {
  if (!state.selectedKey || state.phase === "closing" || lotIsClosed(state.selectedKey)) return;
  if (!window.confirm("Close this SPIN-LOT? This cannot be undone from this page.")) return;
  runClose();
}

function runClose() {
  var lot = LOTS[state.selectedKey];
  var impact = lot.impact || [];
  state.phase = "closing";
  state.closingStep = 0;
  renderDetail();

  clearInterval(state.closingTimer);
  var i = 0;
  state.closingTimer = setInterval(function () {
    i += 1;
    state.closingStep = i;
    renderDetail();
    if (i >= impact.length) clearInterval(state.closingTimer);
  }, 580);

  setTimeout(function () {
    clearInterval(state.closingTimer);
    state.closed.push(state.selectedKey);
    state.phase = "closed";
    state.closingStep = impact.length;
    renderDetail();
    renderList(matchLots());
    flash("SPIN-LOT closed");
  }, 420 + impact.length * 580 + 350);
}

function clearSelection() {
  state.selectedKey = "";
  state.phase = "idle";
  clearDetail();
  renderList(matchLots());
  setStatus(null);
}

function clearDetail() {
  toggle("inv700-detail-content", false);
  toggle("inv700-detail-empty", true);
  toggle("inv700-action-bar", false);
  setStatus(null);
  cancelCountUps();
}

function animateMetric(id, target, decimals) {
  decimals = decimals || 0;
  var el = document.getElementById(id);
  if (!el) return;

  cancelCountUps();
  var t0 = performance.now();
  var duration = 750;

  function tick(now) {
    var p = Math.min(1, (now - t0) / duration);
    var eased = 1 - Math.pow(1 - p, 3);
    var raw = target * eased;
    el.textContent = decimals > 0 ? raw.toFixed(decimals) : Math.round(raw).toLocaleString("en-US");
    if (p < 1) {
      var raf = requestAnimationFrame(tick);
      state.countTimers.push(raf);
    } else {
      el.textContent = decimals > 0 ? target.toFixed(decimals) : target.toLocaleString("en-US");
    }
  }

  state.countTimers.push(requestAnimationFrame(tick));
}

function cancelCountUps() {
  state.countTimers.forEach(function (id) { cancelAnimationFrame(id); });
  state.countTimers = [];
}

function flash(msg) {
  var toast = document.getElementById("inv700-toast");
  toast.textContent = msg;
  toast.classList.remove("inv700-hidden");
  clearTimeout(state.toastTimer);
  state.toastTimer = setTimeout(function () {
    toast.classList.add("inv700-hidden");
  }, 2600);
}

function toggle(id, show) {
  document.getElementById(id).classList.toggle("inv700-hidden", !show);
}

function esc(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/"/g, "&quot;");
}

document.addEventListener("DOMContentLoaded", init);
